// Build client.js from src/core.js + src/features/*.js.
// Feature files are plain JS fragments concatenated inside the client factory
// body (at the `/* __FEATURES__ */` marker). They share the factory closure.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const corePath = join(root, 'src', 'core.js')
const featuresDir = join(root, 'src', 'features')
const outPath = join(root, 'client.js')

const core = readFileSync(corePath, 'utf8')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const version = typeof pkg.version === 'string' && pkg.version ? pkg.version : '0.0.0'
const updatedAt = new Date().toISOString()
const marker = '    /* __FEATURES__ */'
if (!core.includes(marker)) throw new Error('src/core.js is missing the /* __FEATURES__ */ marker')

const files = existsSync(featuresDir)
  ? readdirSync(featuresDir).filter((name) => name.endsWith('.js')).sort()
  : []
const parts = files.map((name) => {
  const body = readFileSync(join(featuresDir, name), 'utf8').replace(/\s+$/, '')
  // Isolate each feature: a load-time failure must not blank the whole panel.
  return `    // ---- src/features/${name} ----\n    ;(() => {\n      try {\n${body}\n      } catch (error) {\n        console.error('[dsh-web-browser] feature \"${name}\" failed to load', error)\n      }\n    })()\n`
})

const output =
  '// Generated by scripts/build.mjs from src/core.js + src/features/*.js. Do not edit directly.\n' +
  core
    .replace(marker, parts.join('\n'))
    .replace(/__DSH_BROWSER_VERSION__/g, version)
    .replace(/__DSH_BROWSER_UPDATED_AT__/g, updatedAt)

writeFileSync(outPath, output, 'utf8')
console.log(
  `built client.js (${output.split('\n').length} lines) from core + ${
    files.length ? files.join(', ') : 'no feature files'
  }`
)
